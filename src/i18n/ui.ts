export type UIKey = keyof (typeof ui)['pl'];

export function t(lang: Lang) {
  return (key: UIKey): string => (ui[lang] as Record<string, string>)[key] ?? ui.pl[key];
}

const BASE = import.meta.env.BASE_URL.replace(/\/$/, '');
/** Adres strony w danym języku: href('en','jobs','operator-linii') → /etatowcy/en/jobs/operator-linii/ */
export function href(lang: Lang, route?: RouteKey, slug?: string): string {
  const parts = [BASE, lang];
  if (route) parts.push(routes[route][lang]);
  if (slug) parts.push(slug);
  return parts.join('/') + '/';
}
